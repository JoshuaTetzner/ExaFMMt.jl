using Exafmmt_jll
using LinearAlgebra
using LinearMaps

abstract type FMMOptions end

"""
    HelmholtzFMMOptions{I, C} <: FMMOptions

Helmholtz initializer for the setup function.

# Fields

  - `p::I`: Multipole expansion order.
  - `ncrit::I`: Minimum number of points in each box of the tree.
  - `wavek::C`: Wavenumber.
"""
struct HelmholtzFMMOptions{I,C} <: FMMOptions
    p::I
    ncrit::I
    wavek::C
end

function HelmholtzFMMOptions(wavek::C; p=8, ncrit=100) where {C<:Complex}
    return HelmholtzFMMOptions(p, ncrit, wavek)
end

"""
    ModifiedHelmholtzFMMOptions{I, F} <: FMMOptions

Modified-Helmholtz initializer for the setup function.

# Fields

  - `p::I`: Multipole expansion order.
  - `ncrit::I`: Minimum number of points in each box of the tree.
  - `wavek::F`: Wavenumber.
"""
struct ModifiedHelmholtzFMMOptions{I,F} <: FMMOptions
    p::I
    ncrit::I
    wavek::F
end

function ModifiedHelmholtzFMMOptions(wavek::F; p=8, ncrit=100) where {F<:Real}
    return ModifiedHelmholtzFMMOptions(p, ncrit, wavek)
end

"""
    LaplaceFMMOptions{I} <: FMMOptions

Laplace initializer for the setup function.

# Fields

  - `p::I`: Multipole expansion order.
  - `ncrit::I`: Minimum number of points in each box of the tree.
"""
struct LaplaceFMMOptions{I} <: FMMOptions
    p::I
    ncrit::I
end

function LaplaceFMMOptions(; p=8, ncrit=100)
    return LaplaceFMMOptions(p, ncrit)
end

function validate_points(points::AbstractMatrix, name::AbstractString)
    size(points, 2) == 3 ||
        throw(ArgumentError("$name must be an n x 3 matrix of 3D points")) # COV_EXCL_LINE
    eltype(points) in (Float32, Float64) || throw(
        ArgumentError(
            "$name must have element type Float32 or Float64; got $(eltype(points))"
        ),
    ) # COV_EXCL_LINE
    return nothing
end

function validate_options(options::FMMOptions)
    options.p isa Integer || throw(ArgumentError("p must be an integer")) # COV_EXCL_LINE
    options.ncrit isa Integer || throw(ArgumentError("ncrit must be an integer")) # COV_EXCL_LINE
    options.p > 0 || throw(ArgumentError("p must be positive")) # COV_EXCL_LINE
    options.ncrit > 0 || throw(ArgumentError("ncrit must be positive")) # COV_EXCL_LINE
    options.p <= typemax(Cint) || throw(ArgumentError("p must fit in Cint")) # COV_EXCL_LINE
    options.ncrit <= typemax(Cint) || throw(ArgumentError("ncrit must fit in Cint")) # COV_EXCL_LINE
    return nothing
end

function validate_setup_inputs(
    sources::AbstractMatrix, targets::AbstractMatrix, options::FMMOptions
)
    validate_points(sources, "sources")
    validate_points(targets, "targets")
    validate_options(options)
    return nothing
end

function setup(sources::Matrix{<:Real}, targets::Matrix{<:Real}, fmmoptions::FMMOptions)
    eltype(sources) === eltype(targets) ||
        throw(ArgumentError("sources and targets must have the same element type")) # COV_EXCL_LINE
    validate_points(sources, "sources")
    validate_points(targets, "targets")
    validate_options(fmmoptions)
    return throw(
        ArgumentError(
            "unsupported combination of coordinate type $(eltype(sources)) and FMM options $(typeof(fmmoptions))",
        ),
    ) # COV_EXCL_LINE
end

"""
    ExaFMM{K, O} <: LinearMaps.LinearMap{K}

Represents an FMM matrix and can be multiplied by a vector containing the source charges.
This type owns C++ storage and releases it through `close!` or its finalizer.

# Fields

  - `fmmoptions::FMMOptions`: Initializer, either `LaplaceFMMOptions`, `HelmholtzFMMOptions`, or `ModifiedHelmholtzFMMOptions`.
  - `nsources::Int`: Number of sources.
  - `ntargets::Int`: Number of targets.
  - `fmm::Ptr{Cvoid}`: Pointer to the FMM struct generated by the C++ part.
  - `fmmstruct::Ptr{Cvoid}`: Pointer to a struct with the required C++ substructs.
  - `sources::Ptr{Cvoid}`: Pointer to the C++ struct of the sources.
  - `targets::Ptr{Cvoid}`: Pointer to the C++ struct of the targets.
"""
mutable struct ExaFMM{K,O<:FMMOptions} <: LinearMaps.LinearMap{K}
    fmmoptions::O
    nsources::Int
    ntargets::Int
    fmm::Ptr{Cvoid}
    fmmstruct::Ptr{Cvoid}
    sources::Ptr{Cvoid}
    targets::Ptr{Cvoid}
    closed::Bool
end

function ExaFMM{K}(
    fmmoptions::O,
    nsources::Integer,
    ntargets::Integer,
    fmm::Ptr{Cvoid},
    fmmstruct::Ptr{Cvoid},
    sources::Ptr{Cvoid},
    targets::Ptr{Cvoid},
) where {K,O<:FMMOptions}
    exafmm = ExaFMM{K,O}(
        fmmoptions, Int(nsources), Int(ntargets), fmm, fmmstruct, sources, targets, false
    )
    finalizer(close!, exafmm)
    return exafmm
end

function check_open(x::ExaFMM)
    x.closed && throw(ArgumentError("ExaFMM object is closed")) # COV_EXCL_LINE
    return nothing
end

"""
    close!(x::ExaFMM)

Release the C++ storage owned by `x`.

Calling `close!` more than once is safe. Closed objects cannot be evaluated or
multiplied again.
"""
function close!(x::ExaFMM)
    x.closed && return nothing

    if x.fmmstruct != C_NULL
        if x isa ExaFMM{<:Union{Float32,Float64}}
            freeF!(x)
        else
            freeC!(x)
        end
    end

    x.fmm = C_NULL
    x.fmmstruct = C_NULL
    x.sources = C_NULL
    x.targets = C_NULL
    x.closed = true

    return nothing
end

Base.close(x::ExaFMM) = close!(x)
Base.eltype(::Type{<:ExaFMM{K}}) where {K} = K
Base.eltype(::ExaFMM{K}) where {K} = K

function validate_charges(A::ExaFMM, x::AbstractVector)
    length(x) == A.nsources || throw(
        DimensionMismatch(
            "charge vector length $(length(x)) does not match number of sources $(A.nsources)",
        ),
    ) # COV_EXCL_LINE
    return nothing
end

# COV_EXCL_START
function evaluate(A::ExaFMM{K}, x::AbstractVector, fmmoptions::FMMOptions) where {K}
    check_open(A)
    validate_charges(A, x)
    return throw(
        ArgumentError(
            "unsupported evaluate call for ExaFMM{$K}, charges $(eltype(x)), and options $(typeof(fmmoptions))",
        ),
    ) # COV_EXCL_LINE
end
# COV_EXCL_STOP

"""
    freeF!(x::ExaFMM{Float64})

Frees the storage which is allocated by the C++ part for the Laplace-FMM and Modified-Helmholtz-FMM.

# Arguments

  - `x::ExaFMM{Float64}`: ExaFMM structure with pointers to all allocated variables.
"""
function freeF!(x::ExaFMM{Float64})
    return ccall(
        (:freestorage_real, libExafmm64),
        Cvoid,
        (Ptr{Cvoid}, Ptr{Cvoid}, Ptr{Cvoid}, Ptr{Cvoid}),
        x.fmm,
        x.fmmstruct,
        x.sources,
        x.targets,
    )
end

