function Base.size(fmm::ExaFMM, dim=nothing)
    if dim === nothing
        return (fmm.ntargets, fmm.nsources)
    elseif dim == 1
        return fmm.ntargets
    elseif dim == 2
        return fmm.nsources
    else
        throw(ArgumentError("dim must be either 1 or 2")) # COV_EXCL_LINE
    end
end

function wrap_c_result(ptr::Ptr{T}, len::Integer) where {T}
    ptr == C_NULL && error("ExaFMMt returned a null result pointer") # COV_EXCL_LINE
    # Exafmmt_jll v0.1.1 allocates these buffers with C++ new[] but exports no
    # matching deallocator, so Julia must not take ownership with own=true.
    return copy(unsafe_wrap(Array, ptr, len; own=false))
end

@views function LinearMaps._unsafe_mul!(y::AbstractVecOrMat, A::ExaFMM, x::AbstractVector)
    check_open(A)

    result = evaluate(A, x, A.fmmoptions)
    potential = view(result, :, 1)

    if y isa AbstractVector
        copyto!(y, potential)
    elseif size(y, 2) == 1
        copyto!(view(y, :, 1), potential)
    else
        throw(DimensionMismatch("output must be a vector or a single-column matrix")) # COV_EXCL_LINE
    end

    return y
end

@views function LinearMaps._unsafe_mul!(
    y::AbstractVecOrMat, transA::LinearMaps.TransposeMap{<:Any,<:ExaFMM}, x::AbstractVector
)
    return throw(
        ArgumentError(
            "transpose multiplication is not implemented for ExaFMM; build a new FMM with sources and targets swapped if you need the transposed operator",
        ),
    ) # COV_EXCL_LINE
end

@views function LinearMaps._unsafe_mul!(
    y::AbstractVecOrMat, transA::LinearMaps.AdjointMap{<:Any,<:ExaFMM}, x::AbstractVector
)
    return throw(
        ArgumentError(
            "adjoint multiplication is not implemented for ExaFMM; build an appropriate swapped/conjugated FMM explicitly",
        ),
    ) # COV_EXCL_LINE
end

"""
    init_sources(points::Matrix{F}, charges::Vector{F}) where F <: Real

Creates struct for sources and charges in the C++ part from the Julia matrix.
Real charges are used and mandatory for the Laplace- and Modified-Helmholtz-FMM.

# Arguments

  - `points::Matrix{F}`: 3d-coordinates of sources.
  - `charges::Vector{F}`: Values of for example the charge at each source location.
"""
function init_sources(points::Matrix{F}, charges::Vector{F}) where {F<:Real}
    validate_points(points, "sources")
    length(charges) == size(points, 1) ||
        throw(DimensionMismatch("charges and sources must have the same length")) # COV_EXCL_LINE

    return init_src(points, charges)
end

function init_src(points::Matrix{Float64}, charges::Vector{Float64})
    return ccall(
        (:init_sources_F, libExafmm64),
        Ptr{Cvoid},
        (Ptr{Float64}, Ptr{Float64}, Cint),
        vec(points),
        charges,
        length(charges),
    )
end

function init_src(points::Matrix{Float32}, charges::Vector{Float32})
    return ccall(
        (:init_sources_F, libExafmm32),
        Ptr{Cvoid},
        (Ptr{Float32}, Ptr{Float32}, Cint),
        vec(points),
        charges,
        length(charges),
    )
end

"""
    init_sources(points::Matrix{F}, charges::Vector{C}) where {F <: Real, C <: Complex}

Creates struct for sources and charges in the C++ part from the Julia matrix.
Complex charges are used for the Helmholtz-FMM.

# Arguments

  - `points::Matrix{F}`: 3d-coordinates of sources.
  - `charges::Vector{C}`: Values of for example the charge at each source location.
"""
function init_sources(points::Matrix{F}, charges::Vector{C}) where {F<:Real,C<:Complex}
    validate_points(points, "sources")
    C === Complex{F} || throw(
        ArgumentError("complex charge type $C must be Complex{$F} for $F coordinates")
    ) # COV_EXCL_LINE
    length(charges) == size(points, 1) ||
        throw(DimensionMismatch("charges and sources must have the same length")) # COV_EXCL_LINE

    return init_src(points, charges)
end

